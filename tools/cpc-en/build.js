// Writes cpc/data-en.js: same bank, English titles and explanations
const fs = require('fs');
const path = require('path');
const { ROOT, hash, loadBank, loadTranslations, topicOrder } = require('./lib');

const bank = loadBank();
const tr = loadTranslations();
const out = {};
let missing = 0;
const en = (text) => tr[hash(text)] || (missing++, null);

for (const key of topicOrder(bank)) {
  const t = bank[key];
  const title = en(t.title);
  const questions = t.questions.map((q) => {
    const exp = en(q.exp);
    return exp === null ? null : { q: q.q, options: q.options, correct: q.correct, exp };
  });
  // A topic is only published once every one of its questions is translated
  if (title !== null && questions.every(Boolean)) out[key] = { title, questions };
}

const body = '// CPC question bank in English, generated by tools/cpc-en/build.js from cpc/data.js. Do not edit by hand.\n'
  + 'window.CPC_TEMAS_EN = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(ROOT, 'cpc', 'data-en.js'), body);
console.log(`topics ready: ${Object.keys(out).length}/${Object.keys(bank).length} · untranslated texts: ${missing}`);
