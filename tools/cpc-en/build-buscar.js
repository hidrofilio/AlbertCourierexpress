// Builds cpc/buscar-en.js (the "find it in the book" tests in English) from cpc/buscar.js.
// Usage: node build-buscar.js            -> writes the file if every text is translated
//        node build-buscar.js pending N  -> lists the first N texts still to translate
// Explanations are translated in tools/cpc-en/tr/*.json, keyed like the rest of the bank.
const fs = require('fs');
const path = require('path');
const { ROOT, hash, loadTranslations } = require('./lib');

const w = { CPC_TEMAS: {} };
new Function('window', fs.readFileSync(path.join(ROOT, 'cpc', 'buscar.js'), 'utf8'))(w);
const tr = loadTranslations();

// The questions quote the exam in English, then add a Spanish hint in brackets: the hint goes
const stripHint = (q) => q.replace(/\n\([^)]*(\([^)]*\)[^)]*)*\)\s*$/, '').trim();
// A few headings end in "(párrafo)": the heading names a paragraph, not a section
const heading = (t) => t.replace(/\(párrafo\)/g, '(paragraph)');

const missing = [];
const seen = new Set();
const T = (text) => {
  const h = hash(text);
  if (tr[h]) return tr[h];
  if (!seen.has(h)) { seen.add(h); missing.push(`${h}\t${text.replace(/\n/g, '\\n')}`); }
  return null;
};

// Summary sheets: module, name, summary pages, [[sheet, missing-in-PDF, items]] — the notes about
// Alberto's own PDF are left out
const resumenes = w.CPC_RESUMENES.map(([n, name, pages, sheets]) => [n, name, pages,
  sheets.map(([sheet, miss, items]) => [sheet, miss, items.map((it) => {
    const out = [heading(it[0]), it[1], it[2] || '', it[3] || 0];
    if (it[4]) out.push([it[4][0]]);
    return out;
  })])]);

const keys = Object.keys(w.CPC_TEMAS).filter((k) => w.CPC_TEMAS[k].type === 'buscar')
  .sort((a, b) => parseInt(a) - parseInt(b));
const tests = {};
keys.forEach((k, n) => {
  tests[k] = {
    title: 'Find it in the book ' + (n + 1),
    type: 'buscar',
    questions: w.CPC_TEMAS[k].questions.map((q) => ({
      q: stripHint(q.q),
      ans: q.ans.map(([m, h]) => [m, heading(h)]),
      exp: T(q.exp)
    }))
  };
});

if (process.argv[2] === 'pending') {
  console.error('pending: ' + missing.length);
  console.log(missing.slice(0, parseInt(process.argv[3] || '100000', 10)).join('\n'));
  process.exit(0);
}
if (missing.length) {
  console.error(`${missing.length} explanations still to translate (node build-buscar.js pending 80)`);
  process.exit(1);
}
// Every answer must point at a heading that exists in that module's summary
let bad = 0;
for (const k of keys) tests[k].questions.forEach((q, i) => q.ans.forEach(([m, h]) => {
  const mod = resumenes.find((r) => r[0] === m);
  if (!mod || !mod[3].some(([, , items]) => items.some((it) => it[0] === h))) { console.error('no heading', k, i, m, h); bad++; }
}));
if (bad) process.exit(1);
fs.writeFileSync(path.join(ROOT, 'cpc', 'buscar-en.js'),
  '// Generated by tools/cpc-en/build-buscar.js from cpc/buscar.js — do not edit by hand\n' +
  'window.CPC_RESUMENES_EN = ' + JSON.stringify(resumenes) + ';\n' +
  'window.CPC_BUSCAR_EN = ' + JSON.stringify(tests).replace(/\},\{"q"/g, '},\n{"q"') + ';\n');
console.log(`find-it tests: ${keys.length} · questions: ${keys.reduce((a, k) => a + tests[k].questions.length, 0)}`);
