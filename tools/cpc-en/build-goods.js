// Builds cpc/data-goods-en.js from tools/cpc-en/goods/*.json
// The goods topics are written in English from official sources (no goods course book yet),
// so each file names its source and every explanation ends with a 📍 line.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const DIR = path.join(__dirname, 'goods');
const out = {};
const seen = new Set();
let total = 0, problems = 0;
const fail = (m) => { console.error('PROBLEM:', m); problems++; };

const files = fs.readdirSync(DIR).filter(f => f.endsWith('.json'))
  .sort((a, b) => parseInt(a.replace(/\D/g, '')) - parseInt(b.replace(/\D/g, '')) || a.localeCompare(b));
for (const f of files) {
  const t = JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8'));
  if (!/^g\w+$/.test(t.key) || out[t.key]) fail(f + ': bad or repeated key ' + t.key);
  t.questions.forEach((q, i) => {
    const where = `${t.key} #${i + 1}`;
    if (!q.q || seen.has(q.q)) fail(where + ': empty or repeated question');
    seen.add(q.q);
    if (!Array.isArray(q.options) || q.options.length !== 4 || new Set(q.options).size !== 4) fail(where + ': needs 4 different options');
    if (!(q.correct >= 0 && q.correct < q.options.length)) fail(where + ': bad correct index');
    if (!q.exp || !q.exp.includes('📍')) fail(where + ': explanation needs a 📍 source line');
    if (/\([A-D]\)|option [A-D]\b/i.test(q.exp)) fail(where + ': explanation must not name options by letter (they are shuffled)');
  });
  out[t.key] = { title: t.title, questions: t.questions.map(({ q, options, correct, exp }) => ({ q, options, correct, exp })) };
  total += t.questions.length;
}
if (problems) process.exit(1);
fs.writeFileSync(path.join(ROOT, 'cpc', 'data-goods-en.js'),
  '// Generated by tools/cpc-en/build-goods.js — edit tools/cpc-en/goods/*.json instead\n' +
  'window.CPC_GOODS_EN = ' + JSON.stringify(out, null, 0).replace(/\},\{"q"/g, '},\n{"q"') + ';\n');
console.log(`goods topics: ${Object.keys(out).length} · questions: ${total}`);
